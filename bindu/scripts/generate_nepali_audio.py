"""Pre-generate Nepali audio (Swar) for EVERY question, answer option, word tile and answer in the lessons,
and host it in the Supabase `audio` bucket (not inside the app), so the app stays small and pronunciation never depends on the Swar tunnel being up.

    python scripts/generate_nepali_audio.py --dry-run      # list what would be spoken, no network
    python scripts/generate_nepali_audio.py --limit 3      # try a few clips first
    python scripts/generate_nepali_audio.py                # synthesise everything that's missing
    python scripts/generate_nepali_audio.py --prune        # also delete clips no lesson uses any more
    python scripts/upload_audio_to_supabase.py --delete-local   # then push the new clips to Supabase (do this after every run)

Reads SWAR_BASE_URL, SWAR_API_KEY, SWAR_VOICE_ID, SWAR_QUALITY from the environment, falling back to backend/.env.
Needs: pyyaml, httpx, and ffmpeg on PATH (WAV -> small mono MP3).

Output
  scripts/audio_out/ne/<hash>.mp3      one clip per unique text (git-ignored; upload_audio_to_supabase.py sends them to the bucket) (hash of voice + quality + text, so changing the voice
                                      makes new clips instead of reusing stale ones; existing clips are skipped on re-runs)
  mobile/lib/audioMap.ts              text -> clip file name. lib/speech.ts plays <bucket>/ne/<name> first, and only asks the
                                      server (or the phone's own voice) for text that has no clip.
  scripts/audio_manifest.json         human-readable text -> file list, with the kind of each string

Run `python scripts/build_lessons_json.py` first if you edited the lesson YAML, so lessons.json and the audio agree.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import time
from pathlib import Path

import httpx
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from nepali_texts import LATIN, ROOT, all_texts  # noqa: E402

SRC = ROOT / "content" / "units.final.yaml"
CLIPS = ROOT / "scripts" / "audio_out" / "ne"  # git-ignored; clips are hosted in Supabase Storage, not bundled
AUDIO_MAP = ROOT / "mobile" / "lib" / "audioMap.ts"
MANIFEST = Path(__file__).resolve().parent / "audio_manifest.json"
MAX_CHARS = 600  # Swar rejects longer text


def load_env_file(path: Path) -> dict[str, str]:
    """Tiny .env reader (KEY=value lines, last one wins), so the script can reuse backend/.env."""
    out: dict[str, str] = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                out[k.strip()] = v.strip().strip("'\"")
    return out


def to_mp3(wav: bytes) -> bytes:
    r = subprocess.run(["ffmpeg", "-v", "error", "-i", "pipe:0", "-ac", "1", "-ar", "24000", "-codec:a", "libmp3lame", "-q:a", "5", "-f", "mp3", "pipe:1"],
                       input=wav, capture_output=True)
    if r.returncode != 0 or not r.stdout:
        raise RuntimeError("ffmpeg failed: " + r.stderr.decode(errors="ignore")[-300:])
    return r.stdout


def clip_name(voice: str, quality: str, text: str) -> str:
    return hashlib.sha1(f"{voice}|{quality}|{text}".encode("utf-8")).hexdigest()[:20] + ".mp3"


def write_audio_map(entries: dict[str, str]) -> None:
    lines = [
        "// AUTO-GENERATED by scripts/generate_nepali_audio.py. Do not edit by hand; re-run the script.",
        "// Nepali text (whitespace-normalised) -> clip file name. The clips live in the Supabase `audio` bucket under ne/ (NOT in the app);",
        "// lib/speech.ts turns a name into a URL and plays it, and only asks the server (or the phone's own voice) if that fails.",
        "/* eslint-disable */",
        "export const NEPALI_AUDIO: Record<string, string> = {",
    ]
    for text, name in entries.items():
        lines.append(f"  {json.dumps(text, ensure_ascii=False)}: {json.dumps(name)},")
    lines.append("};")
    AUDIO_MAP.write_text("\n".join(lines) + "\n", encoding="utf-8")


def synth(http: httpx.Client, base: str, headers: dict, voice: str, quality: str, text: str, retries: int = 3) -> bytes:
    last = ""
    for attempt in range(1, retries + 1):
        try:
            r = http.post(f"{base}/tts", headers=headers, json={"voice_id": voice, "text": text, "quality": quality})
            if r.status_code == 200 and r.content.startswith(b"RIFF"):
                return r.content
            last = f"HTTP {r.status_code}: {r.text[:120]!r}"
        except httpx.HTTPError as e:
            last = f"{type(e).__name__}: {e}"
        time.sleep(2 * attempt)
    raise RuntimeError(last)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true", help="list the texts and counts; no network, no files")
    ap.add_argument("--limit", type=int, default=0, help="only the first N texts")
    ap.add_argument("--quality", choices=["fast", "best"], default=None)
    ap.add_argument("--prune", action="store_true", help="delete clips in assets/audio/ne that no current text uses")
    a = ap.parse_args()

    texts = all_texts(yaml.safe_load(SRC.read_text(encoding="utf-8")))
    items = list(texts.items())
    if a.limit:
        items = items[: a.limit]
    kinds: dict[str, int] = {}
    for _, k in items:
        kinds[k] = kinds.get(k, 0) + 1
    print(f"{len(items)} unique Nepali texts: " + ", ".join(f"{n} {k}" for k, n in kinds.items()))

    problems = [t for t, _ in items if LATIN.search(t) or len(t) > MAX_CHARS]
    for t in problems:
        print(f"  WARNING needs attention (Latin letters or too long): {t!r}. Add it to content/spoken_overrides.json")
    if a.dry_run:
        for t, k in items:
            print(f"  [{k:8}] {t}")
        return 1 if problems else 0

    env = {**load_env_file(ROOT / "backend" / ".env"), **{k: v for k, v in os.environ.items() if k.startswith("SWAR_")}}
    base = env.get("SWAR_BASE_URL", "").rstrip("/")
    if not base:
        sys.exit("Set SWAR_BASE_URL (the current trycloudflare URL from voice.ipynb) in backend/.env or the environment.")
    headers = {"X-API-Key": env["SWAR_API_KEY"]} if env.get("SWAR_API_KEY") else {}
    quality = a.quality or env.get("SWAR_QUALITY", "fast")
    if not subprocess.run(["ffmpeg", "-version"], capture_output=True).returncode == 0:
        sys.exit("ffmpeg is required (WAV -> MP3). Install it and make sure it is on PATH.")

    CLIPS.mkdir(parents=True, exist_ok=True)
    earlier = {t: v["file"] for t, v in json.loads(MANIFEST.read_text(encoding="utf-8")).items()} if MANIFEST.exists() else {}
    done: dict[str, str] = {}
    failed: list[str] = []
    with httpx.Client(timeout=300) as http:
        try:
            voice = env.get("SWAR_VOICE_ID") or http.get(f"{base}/voices", headers=headers).raise_for_status().json()["presets"][0]
        except (httpx.HTTPError, KeyError, IndexError) as e:
            sys.exit(f"Can't reach Swar at {base} ({e}). Is the notebook running, and is SWAR_BASE_URL the CURRENT tunnel URL?")
        print(f"swar={base}  voice={voice}  quality={quality}\n")
        for i, (text, _kind) in enumerate(items, 1):
            name = clip_name(voice, quality, text)
            path = CLIPS / name
            if path.exists() and path.stat().st_size > 0:
                done[text] = name
                print(f"[{i}/{len(items)}] have   {text}")
                continue
            if earlier.get(text) == name:  # same voice+quality+text => same clip; made earlier and already uploaded, so the local copy was deleted
                done[text] = name
                print(f"[{i}/{len(items)}] online {text}")
                continue
            try:
                path.write_bytes(to_mp3(synth(http, base, headers, voice, quality, text)))
                done[text] = name
                print(f"[{i}/{len(items)}] made   {text}  ({path.stat().st_size // 1024} KB)")
            except Exception as e:  # keep going; one bad clip must not lose the rest
                failed.append(text)
                print(f"[{i}/{len(items)}] FAILED {text}: {e}")

    write_audio_map(done)
    kind_of = {t: k for t, k in texts.items()}
    MANIFEST.write_text(json.dumps({t: {"file": n, "kind": kind_of[t]} for t, n in done.items()}, ensure_ascii=False, indent=1), encoding="utf-8")
    if a.prune and not a.limit:
        keep = set(done.values())
        for f in CLIPS.glob("*.mp3"):
            if f.name not in keep:
                f.unlink()
                print(f"pruned {f.name}")
    total_kb = sum((CLIPS / n).stat().st_size for n in done.values() if (CLIPS / n).exists()) // 1024
    new = sum(1 for n in done.values() if (CLIPS / n).exists())
    print(f"\n{len(done)}/{len(items)} clips listed in {AUDIO_MAP.relative_to(ROOT)}; {new} are local ({total_kb} KB) and still need uploading:")
    print("  python scripts/upload_audio_to_supabase.py --delete-local")
    if failed:
        print(f"{len(failed)} failed; run the script again to retry just those:")
        for t in failed:
            print("  ", t)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
